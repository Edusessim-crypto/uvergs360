function buildFiller(): Base[] {
  const rnd = createRandom(2718)
  const offsets = rnd.shuffle(Array.from({ length: 330 }, (_, i) => i + 6).filter((d) => ![25, 26, 27, 41, 56, 71, 84, 85, 86].includes(d))).slice(0, FILLER_TEMPLATES.length).sort((a, b) => a - b)
  return FILLER_TEMPLATES.map((t, i) => {
    const online = t.format === "Online"
    const capacity = online ? rnd.pick([300, 500, 800]) : rnd.pick([120, 150, 200])
    const registered = Math.round(capacity * rnd.float(0.52, 0.93))
    const present = Math.round(registered * rnd.float(0.74, 0.9))
    const start = daysAgo(offsets[i], online ? 19 : 8, online ? 0 : 30)
    return {
      id: `ev-${slugify(t.title)}`,
      title: t.title,
      type: t.type,
      format: t.format,
      startDate: start,
      endDate: start,
      city: t.city ?? "Online",
      regionId: t.regionId ?? "metropolitana",
      venue: online ? "Transmissão ao vivo" : `Auditório Regional — ${t.city}`,
      address: online ? "Plataforma UVERGS" : `${t.city}/RS`,
      capacity,
      registered,
      paymentsConfirmed: Math.round(registered * 0.95),
      present,
      chambersCount: Math.round(registered * rnd.float(0.35, 0.55)),
      municipalitiesCount: Math.round(registered * rnd.float(0.32, 0.5)),
      certificatesIssued: Math.round(present * 0.97),
      nps: rnd.int(58, 79),
      status: "encerrado" as EventStatus,
      price: online ? 0 : 150,
      priceNonMember: online ? 0 : 220,
      workload: online ? (t.type === "Curso" ? 12 : 2) : 8,
      description: `${t.type} promovido pela UVERGS.`,
      audience: "Vereadores e servidores",
    }
  })
}

export function buildEvents(): UvergsEvent[] {
  return [...HANDCRAFTED, ...buildFiller()].map((e) => ({
    ...e,
    slug: slugify(e.title.replace(/UVERGS \d+/, "UVERGS")),
    program: e.program ?? ONE_DAY_PROGRAM,
    speakers: e.speakers ?? [SPEAKERS.bittencourt],
    createdAt: daysAgo(120),
  }))
}
